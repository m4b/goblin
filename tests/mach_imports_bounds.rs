/// Regression tests for the crafted-Mach-O panics reported in #542.
///
/// Both inputs are the byte-for-byte PoCs from that report: a 79 byte Mach-O
/// that made `imports()` index an empty segment list, and an 89 byte Mach-O
/// whose `LC_SYMTAB` claims 4294967295 symbols in a file of 89 bytes.
///
/// The point of these tests is that the library must fail with a parse error
/// instead of panicking or exhausting memory. A panic in a parser that runs on
/// untrusted input is a denial of service, so `catch_unwind` is used to turn a
/// regression back into a test failure rather than aborting the whole run.
use goblin::mach::Mach;
use std::panic::{AssertUnwindSafe, catch_unwind};

