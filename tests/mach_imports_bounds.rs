/// Control: a well-formed single-arch Mach-O must still parse its imports.
/// If this regresses the bounds check is too strict and real binaries are
/// being rejected, which is worse than the panic.
#[test]
fn valid_binary_still_parses_imports() {
    match Mach::parse(&DEADBEEF_MACH_64[..]).unwrap() {
        Mach::Binary(ref m) => {
            // Either outcome is fine; what matters is that it does not panic
            // and does not error on a binary we know is well formed.
            if let Ok(imports) = m.imports() {
                for import in &imports {
                    assert!(
                        !import.dylib.is_empty(),
                        "an import was produced with an empty dylib name",
                    );
                }
            }
        }
        Mach::Fat(_) => panic!("expected a single-arch binary"),
    }
}
